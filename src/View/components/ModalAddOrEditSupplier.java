    private void ButtonSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtonSimpanActionPerformed
        if(this.isAdd){
            SupplierInterface add = new SupplierInterface(
                    this.InputTextNama.getText(),
                    this.InputTextAlamatLengkap.getText(),
                    this.InputTextNomorHp.getText()
            );
            
            try {
                this.supplierControler.addSupplier(add);
            } catch (SQLException ex) {
                this.TextError.setText(ex.getMessage());
                System.getLogger(ModalAddOrEditSupplier.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }finally{
                this.closeWindow();
            }
        }
    }//GEN-LAST:event_ButtonSimpanActionPerformed

