    private String formatRupiahAman(Object nilai) {
        if (nilai == null) {
            return "Rp. 0";
        }
        String teks = nilai.toString().trim();
        if (teks.isEmpty()) {
            return "Rp. 0";
        }
        return teks.startsWith("Rp") ? teks : "Rp. " + teks;
    }

    public void updateKeranjang(javax.swing.table.DefaultTableModel modelKasir,
            String subTotal, String pajak, String grandTotal) {
        if (modelKasir == null) {
            return;
        }

        javax.swing.SwingUtilities.invokeLater(() -> {
            javax.swing.table.DefaultTableModel modelLayar2 =
                    (javax.swing.table.DefaultTableModel) TabelBelanjaLayar2.getModel();
            modelLayar2.setRowCount(0);

            int jumlahKolom = modelKasir.getColumnCount();
            for (int i = 0; i < modelKasir.getRowCount(); i++) {
                Object nama = jumlahKolom > 1 ? modelKasir.getValueAt(i, 1) : "";
                Object jumlah = jumlahKolom > 2 ? modelKasir.getValueAt(i, 2) : 0;
                Object satuan = jumlahKolom > 3 ? modelKasir.getValueAt(i, 3) : "";
                Object hargaAkhir = jumlahKolom > 6 ? modelKasir.getValueAt(i, 6) : 0;
                Object total = jumlahKolom > 7 ? modelKasir.getValueAt(i, 7) : 0;

                modelLayar2.addRow(new Object[]{
                    (i + 1),
                    nama,
                    jumlah,
                    satuan,
                    formatRupiahAman(hargaAkhir),
                    formatRupiahAman(total)
                });
            }

            LabelTotalBesar.setText(formatRupiahAman(grandTotal));
            LabelSubTotal.setText(formatRupiahAman(subTotal));
            LabelPajak.setText(formatRupiahAman(pajak));
            LabelGrandTotal.setText(formatRupiahAman(grandTotal));
        });
    }

    public void updatePembayaran(String metode, String dibayar, String kembalian, String pesanInfo) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            LabelMetode.setText((metode != null && !metode.isBlank()) ? metode : "-");
            LabelDibayar.setText(formatRupiahAman(dibayar));
            LabelKembalian.setText(formatRupiahAman(kembalian));
            if (pesanInfo != null && !pesanInfo.isBlank()) {
                jLabel16.setText(pesanInfo);
            }
        });
    }

    public void resetLayar() {
        javax.swing.SwingUtilities.invokeLater(() -> {
            javax.swing.table.DefaultTableModel modelLayar2 =
                    (javax.swing.table.DefaultTableModel) TabelBelanjaLayar2.getModel();
            modelLayar2.setRowCount(0);
            LabelTotalBesar.setText("Rp. 0");
            LabelSubTotal.setText("Rp. 0");
            LabelPajak.setText("Rp. 0");
            LabelGrandTotal.setText("Rp. 0");
            LabelMetode.setText("-");
            LabelDibayar.setText("Rp. 0");
            LabelKembalian.setText("Rp. 0");
            jLabel16.setText("Terima Kasih Telah Berbelanja!");
        });
    }
    
    public void tutupLayar() {
        javax.swing.SwingUtilities.invokeLater(() -> {
            resetLayar();
            dispose();
        });
    }

